#!/usr/bin/env node
/* ============================================================================
 * docsify-isf — K4 build
 *
 * Builds the single-file UMD artifact from two sources:
 *   1. the vendored canonical kernel (`vendor/isf-core/`, synced from the
 *      parent repo with `scripts/isf-plugin-sync.mjs`), bundled as `ISFCore`;
 *   2. `src/plugin.src.js` — the Docsify/UI layer with the old copies of the
 *      compiler functions removed and the adapter (`src/kernel-adapter.js`)
 *      injected in their place.
 *
 *   node tools/build.mjs            # write docsify-isf.js
 *   node tools/build.mjs --check    # fail when the artifact is out of date
 * ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import esprima from 'esprima';
import { buildBundle } from '../vendor/bundle-lib.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const OUT = path.join(ROOT, 'docsify-isf.js');
const SRC = path.join(ROOT, 'src', 'plugin.src.js');
const ADAPTER = path.join(ROOT, 'src', 'kernel-adapter.js');
const SENTINEL = '    /* @isf-core:inject — the vendored kernel bundle and adapter are generated here by tools/build.mjs */';

// Compiler functions that now live in the core. The adapter below redefines
// the entry points; anything else in this list must have no remaining
// references (the build fails loudly otherwise).
const ADAPTER_PROVIDES = [
    'parseISF', 'parseISFMetadata', 'parseJSONTolerant',
    'normalizeInputs', 'normalizePasses', 'normalizeGenerators', 'normalizeImports',
    'buildShader', 'createGenerators',
];
const REMOVE = [
    'parseJSONTolerant', 'parseISFMetadata', 'parseISF',
    'firstDefined', 'pairValue', 'quadValue',
    'normalizeInputs', 'normalizePasses', 'normalizeGenerators', 'normalizeImports',
    'defaultVertexShader', 'stripVersionDirective', 'expandIncludes', 'stripComments',
    'analyzeDeclarationScopes', 'findMatchingParen', 'intDeclarationHasFloat',
    'splitTopLevelArguments', 'argumentLooksFloat', 'argumentLooksInt',
    'coerceBuiltinArguments', 'lowerIntegerPowers', 'promoteIntegerLiterals',
    'stripCommentsPreservingLines', 'hasTopLevelComma', 'hoistGlobalInitializers',
    'toES3Fragment', 'toES3Vertex', 'buildVertexShader',
    'collectUserFunctions', 'collectDeclaredTypes', 'valueDim',
    'callArgumentTexts', 'resolveLibraryRename', 'rewriteLibraryCalls',
    'aliasPreludeLines', 'isInsideESGuardedBlock', 'collectFunctionSignatures',
    'promoteTypeToFloat', 'castToOriginalType', 'buildOverloadShims',
    'replaceIdentifiers', 'normalizeTypeKeywords', 'normalizeNumericSuffixes',
    'constantPreludeLines', 'renameBuiltinShadows', 'demoteAssignedUniforms',
    'buildShader',
    'createGenerators',
];

const CORE_MODULES = [
    'isf-core/compat.js',
    'isf-core/parse.js',
    'isf-core/generators.js',
    'isf-core/render.js',
    'isf-core/api.js',
];

function coreBundle() {
    const bundle = buildBundle({
        root: path.join(ROOT, 'vendor'),
        modules: CORE_MODULES,
        header: 'vendored ISF core — generated by tools/build.mjs; do not edit',
    });
    // The bundler's IIFE does not return its modules; expose the API object as
    // a local so the artifact works in Node (tests) and in the browser.
    const withReturn = bundle.replace(/\}\)\(\);\s*$/, "  return __modules['isf-core/api.js'].default;\n})();\n");
    if (withReturn === bundle) throw new Error('build: could not find the bundle epilogue');
    // The core is a source artifact, not a human-facing file: strip its
    // comments and blank lines to keep the single-file plugin lean.
    return '    var ISFCore = ' + stripCoreComments(withReturn).split('\n').join('\n    ');
}

/** Blank comments and string contents so identifier checks only see code. */
function blankCommentsAndStrings(source) {
    let out = '';
    let i = 0;
    while (i < source.length) {
        const c = source[i];
        if (c === '/' && source[i + 1] === '/') {
            while (i < source.length && source[i] !== '\n') { out += ' '; i += 1; }
            continue;
        }
        if (c === '/' && source[i + 1] === '*') {
            while (i < source.length && !(source[i] === '*' && source[i + 1] === '/')) { out += source[i] === '\n' ? '\n' : ' '; i += 1; }
            out += '  '; i += 2;
            continue;
        }
        if (c === '"' || c === "'" || c === '`') {
            const quote = c;
            out += quote; i += 1;
            while (i < source.length && source[i] !== quote) {
                if (source[i] === '\\') { out += '  '; i += 2; continue; }
                out += source[i] === '\n' ? '\n' : ' ';
                i += 1;
            }
            if (i < source.length) { out += quote; i += 1; }
            continue;
        }
        out += c;
        i += 1;
    }
    return out;
}

/** Strip the generated core bundle's comments, string/regex-aware. */
function stripCoreComments(source) {
    const keywords = new Set(['return', 'typeof', 'case', 'delete', 'void', 'in', 'of',
        'instanceof', 'new', 'do', 'else', 'yield', 'await', 'throw']);
    let out = '';
    let i = 0;
    let prevChar = '';
    let prevWord = '';
    const regexAllowed = () => {
        if (keywords.has(prevWord)) return true;
        return prevChar === '' || '(,=:[!&|?{};+-*%^<>~'.includes(prevChar);
    };
    while (i < source.length) {
        const c = source[i];
        if (c === '/' && source[i + 1] === '/') {
            while (i < source.length && source[i] !== '\n') i += 1;
            continue;
        }
        if (c === '/' && source[i + 1] === '*') {
            i += 2;
            while (i < source.length && !(source[i] === '*' && source[i + 1] === '/')) i += 1;
            i += 2;
            continue;
        }
        if (c === '/' && regexAllowed()) {
            out += c; i += 1;
            let inClass = false;
            while (i < source.length) {
                const ch = source[i];
                out += ch;
                if (ch === '\\') { out += source[i + 1] || ''; i += 2; continue; }
                if (ch === '[') inClass = true;
                else if (ch === ']') inClass = false;
                else if (ch === '/' && !inClass) { i += 1; break; }
                i += 1;
            }
            while (i < source.length && /[a-z]/i.test(source[i])) { out += source[i]; i += 1; }
            prevChar = '/'; prevWord = '';
            continue;
        }
        if (c === '"' || c === "'" || c === '`') {
            const quote = c;
            out += quote; i += 1;
            while (i < source.length && source[i] !== quote) {
                if (source[i] === '\\') { out += source[i] + (source[i + 1] || ''); i += 2; continue; }
                out += source[i]; i += 1;
            }
            if (i < source.length) { out += quote; i += 1; }
            prevChar = quote; prevWord = '';
            continue;
        }
        out += c;
        if (/[A-Za-z0-9_$]/.test(c)) prevWord = (prevWord + c).replace(/^.*?([A-Za-z_$][A-Za-z0-9_$]*)$/, '$1');
        if (!/\s/.test(c)) { prevChar = c; if (!/[A-Za-z0-9_$]/.test(c)) prevWord = ''; }
        i += 1;
    }
    return out.split('\n').map((line) => line.replace(/[ \t]+$/, '')).filter((line, index, all) => line.trim() !== '' || (index > 0 && all[index - 1].trim() !== '')).join('\n');
}

function functionRanges(source) {
    const ast = esprima.parseScript(source, { tolerant: true, range: true, comment: true });
    const factory = ast.body[0].expression.arguments[1];
    const ranges = new Map();
    for (const node of factory.body.body) {
        if (node.type === 'FunctionDeclaration' && node.id) ranges.set(node.id.name, node.range);
        // `var createGenerators = (function () { … })();` and friends
        if (node.type === 'VariableDeclaration') {
            for (const decl of node.declarations) {
                if (decl.id && decl.id.type === 'Identifier') ranges.set(decl.id.name, node.range);
            }
        }
    }
    return ranges;
}

function build() {
    const source = fs.readFileSync(SRC, 'utf8');
    if (!source.includes(SENTINEL)) throw new Error('build: src/plugin.src.js is missing the injection sentinel');
    const ranges = functionRanges(source);

    const missing = REMOVE.filter((name) => !ranges.has(name));
    if (missing.length) throw new Error('build: functions to remove not found: ' + missing.join(', '));

    // Remove the old copies, largest offset first so the ranges stay valid.
    const cuts = [...new Set(REMOVE.map((name) => ranges.get(name).join(':')))]
        .map((key) => key.split(':').map(Number))
        .sort((a, b) => b[0] - a[0]);
    let stripped = source;
    for (const [start, end] of cuts) stripped = stripped.slice(0, start) + stripped.slice(end);

    // Safety net: nothing may still call a removed function unless the
    // adapter redefines it. Comments and string literals are ignored so a
    // doc comment naming the old helper is not a false positive.
    const codeOnly = blankCommentsAndStrings(stripped);
    const leftover = [];
    for (const name of REMOVE) {
        if (ADAPTER_PROVIDES.includes(name)) continue;
        const re = new RegExp('\\b' + name + '\\b');
        if (re.test(codeOnly)) leftover.push(name);
    }
    if (leftover.length) throw new Error('build: removed functions still referenced: ' + leftover.join(', '));

    const adapter = fs.readFileSync(ADAPTER, 'utf8').replace(/\s+$/, '');
    const injected = [
        '    /* ==================================================================',
        '     * K4 — the compiler kernel is the shared core (vendor/isf-core).',
        '     * Generated by tools/build.mjs from src/kernel-adapter.js; edit the',
        '     * adapter or the vendored core, never the artifact.',
        '     * ================================================================== */',
        '',
        coreBundle(),
        '',
        adapter,
    ].join('\n');
    const artifact = stripped.replace(SENTINEL, SENTINEL + '\n\n' + injected);
    return artifact;
}

const artifact = build();
if (CHECK) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== artifact) {
        console.log('build --check: docsify-isf.js is out of date — run node tools/build.mjs');
        process.exit(1);
    }
    console.log('build --check: docsify-isf.js is up to date');
} else {
    fs.writeFileSync(OUT, artifact);
    console.log('build: wrote docsify-isf.js (' + artifact.length + ' bytes)');
}
